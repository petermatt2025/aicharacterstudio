// UI + server definitions for implemented generator tools. Client-safe (no secrets).
import type { AspectRatio, Quality, ReferenceRole } from "@/server/providers/types";

export type Slot = {
  role: ReferenceRole;
  label: string;
  hint: string;
  required: boolean;
  uploadKind: "character" | "product" | "outfit" | "background" | "style" | "other";
  /** How this reference is described to the model (overrides the role's default wording). */
  promptLabel?: string;
  /** The slot shows a real person: only consented Character uploads are accepted. */
  person?: boolean;
  /** The picker also offers images generated in this app (Gallery outputs). */
  pickOutputs?: boolean;
};
export type Preset = {
  key: string;
  label: string;
  prompt: string;
  requires?: ReferenceRole;
  /** Per-image aspect ratio (multi-format tools); falls back to the job's ratio. */
  aspect?: AspectRatio;
  /** A sequence of beats: the preset expands into one image per beat (storyboards, keyframes). */
  recipe?: string[];
  /** Outpaint: the source image is placed on a larger canvas of `aspect` and the model fills the border. */
  outpaint?: boolean;
  /** The user must describe the change in the prompt box. */
  needsPrompt?: boolean;
  /** A style board must be chosen. */
  needsStyle?: boolean;
};

export type ToolDef = {
  key: string;
  title: string;
  tagline: string;
  instructions: string[];
  examples: string[];
  warnings: string[];
  slots: Slot[];
  presetLabel: string;
  presets: Preset[];
  /** "shots": each selected preset becomes its own output. "single": presets are style chips merged into one prompt. */
  presetMode: "shots" | "single";
  minPresets: number;
  maxPresets: number;
  defaultPresets: string[];
  defaultAspect: AspectRatio;
  allowVariations: boolean; // outputs per shot
  promptPlaceholder: string;
  promptRequired: boolean;
  creditRule: "auto" | "angle_sheet" | "photoshoot" | "video";
  /** Output type (default image). Video tools run through the video engine. */
  output?: "image" | "video";
};

